// Regenerates src/subdivisionCodes.ts from dr5hn/countries-states-cities-database.
//
// WHAT THIS IS FOR. "Chennai, TN" was stored as Tennessee, "Sao Paulo, MA" as Massachusetts,
// "Tbilisi, Georgia" as Georgia the US state. All three are the same shape: a world city followed by
// a subdivision code that collides with a US state abbreviation. It is the standard output of
// Workable, Recruitee and Personio, which compose the location from separate city/region/country
// fields where the country field is often blank.
//
// The obvious repair — "if the city says a non-US country, drop the state" — was implemented and
// MEASURED and is worse than the bug: it turns "Berlin, NH" into Germany and "Paris, TX" into
// France, because the city tier only knows one Berlin and one Paris. What is missing is
// CORROBORATION: is that two-letter token actually a subdivision of the country the city names?
//   Chennai + TN  -> TN is Tamil Nadu in IN, and the city says IN     -> agree, it is not Tennessee
//   Berlin  + NH  -> NH is not a German state, whatever the city says -> keep New Hampshire
//
// src/places.ts cannot answer that: it maps subdivision NAMES, and deliberately drops any name that
// occurs in two countries. This is a separate, much smaller table of CODES, so it is generated into
// its own file rather than growing that one.
//
// Two tables come out of it:
//   SUB_CODES      two-letter subdivision code -> the countries that use it
//   COUNTRY_ALIAS  country name -> ISO code, INCLUDING the ambiguous ones places.ts drops. "Georgia"
//                  is the whole reason: places.ts cannot hold it (US state and country), but paired
//                  with a city that resolves to GE it decides "Tbilisi, Georgia" correctly.
//
// Generated and committed for the same reasons as places.ts: reference data that changes a few times
// a decade, read on a hot path, and the app must work offline.
//
// Usage:  node scripts/gen-subdivision-codes.mjs
import { writeFileSync } from "node:fs";

const BASE = "https://raw.githubusercontent.com/dr5hn/countries-states-cities-database/master/json";
const get = async (f) => {
  const r = await fetch(`${BASE}/${f}`);
  if (!r.ok) throw new Error(`HTTP ${r.status} fetching ${f}`);
  return r.json();
};

const fold = (s) => String(s ?? "").normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase()
  .replace(/[^\p{L}\p{N}]+/gu, " ").replace(/\s+/g, " ").trim();

// ---- subdivision codes --------------------------------------------------------------------------
const states = await get("states.json");
const codes = new Map(); // "TN" -> Set("IN","US",…)
for (const s of states) {
  const cc = String(s.country_code ?? "").toUpperCase();
  // `iso2` on a state row is the SUBDIVISION part of its ISO 3166-2 code ("IN-TN" -> "TN"), not a
  // country code. There is no `state_code` field; the first version of this script assumed one and
  // silently emitted an empty table, which would have made the whole corroboration rule a no-op that
  // still looked like it was working.
  const code = String(s.iso2 ?? "").toUpperCase();
  if (!/^[A-Z]{2}$/.test(cc) || !/^[A-Z]{2}$/.test(code)) continue;
  if (!codes.has(code)) codes.set(code, new Set());
  codes.get(code).add(cc);
}
console.log(`subdivision codes: ${codes.size}`);

// ---- country names, ambiguous ones INCLUDED -----------------------------------------------------
// Unlike places.ts this keeps a name that is also a US state, because the caller only ever consults
// it together with a city that already points at a country — the pair is the evidence, not the name.
const countries = await get("countries.json");
const alias = new Map();
for (const c of countries) {
  const cc = String(c.iso2 ?? "").toUpperCase();
  if (!/^[A-Z]{2}$/.test(cc)) continue;
  for (const n of [c.name, c.native]) {
    const f = fold(n);
    if (f && f.length >= 4 && !alias.has(f)) alias.set(f, cc);
  }
}
console.log(`country aliases:   ${alias.size}`);

const blob = (rows) => rows.map(([k, v]) => `${k}\t${v}`).join("\n");
const subRows = [...codes].sort((a, b) => a[0].localeCompare(b[0])).map(([k, v]) => [k, [...v].sort().join(",")]);
const aliasRows = [...alias].sort((a, b) => a[0].localeCompare(b[0]));

writeFileSync(new URL("../src/subdivisionCodes.ts", import.meta.url), `\
// GENERATED by scripts/gen-subdivision-codes.mjs — do not edit by hand. Re-run that script to update.
// Source: dr5hn/countries-states-cities-database (states.json, countries.json).
//
// Two-letter subdivision codes and the countries that use them, plus country names INCLUDING the
// ambiguous ones src/places.ts has to drop. Used by deriveState to CORROBORATE a city's country
// against the region code beside it — see that function and the generator's header for why a bare
// "the city says a foreign country" rule is not good enough.

const SUB_CODES = \`${blob(subRows)}\`;
const COUNTRY_ALIAS = \`${blob(aliasRows)}\`;

const parse = (s: string): Map<string, string> => {
  const m = new Map<string, string>();
  for (const line of s.split("\\n")) { const i = line.indexOf("\\t"); if (i > 0) m.set(line.slice(0, i), line.slice(i + 1)); }
  return m;
};
let subs: Map<string, string> | null = null;
let names: Map<string, string> | null = null;

/** Is this two-letter code a subdivision of that country? ("TN", "IN") -> true (Tamil Nadu). */
export function isSubdivisionCodeOf(code: string, cc: string): boolean {
  const row = (subs ??= parse(SUB_CODES)).get(code.toUpperCase());
  return !!row && row.split(",").includes(cc.toUpperCase());
}

/** ISO code for a country NAME, ambiguous ones included ("georgia" -> "GE"). Folded input. */
export function countryCodeByName(folded: string): string | null {
  return (names ??= parse(COUNTRY_ALIAS)).get(folded) ?? null;
}
`);
console.log("wrote src/subdivisionCodes.ts");
